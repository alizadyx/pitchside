#!/usr/bin/env python3
"""Turn the FM27 preset workbooks (one per style: Presets / Roles / Instructions sheets)
into app/Sources/PitchsideCore/FMPresetData.swift.  Usage: presets_to_swift.py DIR"""
import sys, glob, os, openpyxl

POS = {"GK": "GK", "D (R)": "DR", "D (C)": "DC", "D (L)": "DL", "WB (R)": "WBR", "WB (L)": "WBL",
       "DM": "DM", "M (R)": "MR", "M (C)": "MC", "M (L)": "ML", "AM (R)": "AMR", "AM (C)": "AMC",
       "AM (L)": "AML", "ST (C)": "ST"}
IP = {"GK": "GK", "BGK": "BPGK", "NGK": "NNGK", "CB": "CB", "BCB": "BPCB", "ACB": "ACB", "NCB": "NNCB",
      "WCB": "WCB", "OCB": "OCB", "FB": "FB", "IFB": "IFB", "WB": "WB", "IWB": "IWB", "PWB": "PWB",
      "AWB": "AWB", "DM": "DM", "DLP": "DLP", "BBM": "B2B", "BBP": "B2BP", "HB": "HB", "CM": "CM",
      "WCM": "WCM", "MPM": "MP", "CHM": "CHM", "AP": "AP", "AM": "AM", "FR": "FR", "SS": "SS",
      "WM": "WM", "W": "W", "IW": "IW", "PW": "PW", "IF": "IF", "WFD": "WF", "CFD": "CF", "TF": "TF",
      "TGF": "TF", "P": "P", "PCH": "P", "CHF": "CHF", "DLF": "DLF", "F9": "F9", "FN": "F9"}
OOP = {"GK": "oGK", "SK": "oSK", "LK": "oLK", "CB": "oCB", "SCB": "oSCB", "CCB": "oCCB", "WCB": "oWCB",
       "SWD": "oSWCB", "SWC": "oSWCB", "CWD": "oCWCB", "CWC": "oCWCB", "FB": "oFB", "PFB": "oPFB",
       "HFB": "oHFB", "WB": "oWB", "PWB": "oPWB", "HWB": "oHWB", "DM": "oDM", "DDM": "oDDM",
       "PDM": "oPDM", "SDM": "oSDM", "WDM": "oWCDM", "CM": "oCM", "PCM": "oPCM", "SCM": "oSCM",
       "WCM": "oWCCM", "WMF": "oWM", "TWM": "oTWM", "OWM": "oWOWM", "W": "oW", "TW": "oTW",
       "IOW": "oIOW", "WOW": "oWOW", "AM": "oAM", "TAM": "oTAM", "OAM": "oCOAM", "SAM": "oSOAM",
       "CFD": "oCF", "TCF": "oTCF", "OCF": "oCOCF", "SCF": "oSOCF"}

def rows(ws):
    return [r for r in ws.iter_rows(min_row=4, values_only=True)]

def q(s): return '"' + str(s).replace('"', '\\"') + '"'

styles, presets, missing = [], [], set()
for f in sorted(glob.glob(os.path.join(sys.argv[1], "*.xlsx"))):
    wb = openpyxl.load_workbook(f, data_only=True)
    ps = [r for r in rows(wb["Presets"]) if r[0] and isinstance(r[1], int)]
    style, ment = ps[0][2], ps[0][5]
    roles = {}
    for r in rows(wb["Roles"]):
        if r[0] and isinstance(r[1], int) and r[2]:
            roles.setdefault(r[0], []).append(r)
    for p in ps:
        slots = []
        for r in sorted(roles[p[0]], key=lambda r: r[1]):
            ip, op = IP.get(r[3]), OOP.get(r[5])
            if not ip: missing.add("IP " + r[3])
            if not op: missing.add("OOP " + r[5])
            slots.append(f"{POS[r[2]]} {ip or r[3]} {POS[r[4]]} {op or r[5]}")
        presets.append(f"        FMPreset(id: {q(p[0])}, style: {q(style)}, ip: {q(p[3])}, oop: {q(p[4])}, slots: {q('|'.join(slots))}),")
    ins = [r for r in rows(wb["Instructions"]) if r[0] in ("IP", "OOP") and r[3] and "screenshot" not in str(r[2])]
    items = ", ".join(f"[{q(r[0])}, {q(r[1])}, {q(r[2])}, {q(r[3])}]" for r in ins)
    styles.append(f"        FMStyle(name: {q(style)}, mentality: {q(ment)}, instructions: [{items}]),")

out = ["// Generated by tools/presets_to_swift.py from the FM27 preset workbooks. Do not edit by hand.",
       "", "extension FMPresets {", "    public static let styles: [FMStyle] = ["] + styles + ["    ]",
       "    public static let all: [FMPreset] = ["] + presets + ["    ]", "}", ""]
dst = os.path.join(os.path.dirname(__file__), "../app/Sources/PitchsideCore/FMPresetData.swift")
open(dst, "w").write("\n".join(out))
print(len(styles), "styles,", len(presets), "presets; unmapped:", sorted(missing) or "none")
